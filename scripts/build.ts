/**
 * Build: the report's assets, the npm bundle and the standalone binaries.
 *
 *   bun scripts/build.ts --assets          report/ → src/report/assets.gen.ts (what the CLI embeds)
 *   bun scripts/build.ts                   assets + dist/explain-change.js (Node ≥ 20, no dependencies)
 *   bun scripts/build.ts --compile [t…]    assets + standalone binaries in dist/bin (all targets by default)
 *   bun scripts/build.ts --schemas         schemas/*.schema.json from the contract (committed; a test checks them)
 *
 * The report script is bundled without minification: the same source always gives the same page, and a reader can
 * open it.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ensureDir } from "../src/core/fs.ts";

const ROOT = join(import.meta.dir, "..");
const GENERATED = join(ROOT, "src/report/assets.gen.ts");
export const TARGETS = [
  "bun-linux-x64",
  "bun-linux-arm64",
  "bun-darwin-x64",
  "bun-darwin-arm64",
  "bun-windows-x64",
] as const;

/** report/logo.svg as a data: URI, for favicons. */
export function logoDataUri(): string {
  const svg = readFileSync(join(ROOT, "report/logo.svg"), "utf8")
    .trim()
    .replace(/\s*\n\s*/g, " ");
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

/** Bundles report/app.ts and writes the assets module, only when it changed. Returns whether it did. */
export async function buildAssets(): Promise<boolean> {
  const out = await Bun.build({
    entrypoints: [join(ROOT, "report/app.ts")],
    target: "browser",
    format: "iife",
    minify: false,
  });
  if (!out.success) throw new AggregateError(out.logs, "report/app.ts does not build");
  const js = await (out.outputs[0] as Blob).text();
  const css = readFileSync(join(ROOT, "report/styles.css"), "utf8");
  const html = readFileSync(join(ROOT, "report/index.html"), "utf8").replace("{{ICON}}", () => logoDataUri());
  const text =
    "// Generated by scripts/build.ts from report/: do not edit.\n" +
    `export const REPORT_HTML = ${JSON.stringify(html)};\n` +
    `export const REPORT_CSS = ${JSON.stringify(css)};\n` +
    `export const REPORT_JS = ${JSON.stringify(js)};\n`;
  if (existsSync(GENERATED) && readFileSync(GENERATED, "utf8") === text) return false;
  writeFileSync(GENERATED, text);
  return true;
}

async function buildNode() {
  const out = await Bun.build({
    entrypoints: [join(ROOT, "src/cli/bin.ts")],
    target: "node",
    format: "esm",
    minify: false,
  });
  if (!out.success) throw new AggregateError(out.logs, "the CLI does not build");
  ensureDir(join(ROOT, "dist"));
  const file = join(ROOT, "dist/explain-change.js");
  writeFileSync(file, await (out.outputs[0] as Blob).text(), { mode: 0o755 });
  console.log(`built ${file}`);
}

function compile(targets: string[]): void {
  for (const target of targets) {
    const name = `explain-change-${target.replace(/^bun-/, "")}${target.includes("windows") ? ".exe" : ""}`;
    compileBinary(join(ROOT, "dist/bin", name), target);
  }
}

/** One standalone binary of the CLI, for a Bun target ("bun-linux-x64", …) or, without one, for this machine. */
export function compileBinary(outfile: string, target?: string): void {
  ensureDir(dirname(outfile));
  const p = Bun.spawnSync(
    [
      "bun",
      "build",
      "--compile",
      ...(target ? [`--target=${target}`] : []),
      join(ROOT, "src/cli/bin.ts"),
      "--outfile",
      outfile,
    ],
    { stdout: "inherit", stderr: "inherit" },
  );
  if (p.exitCode !== 0) throw new Error(`compile ${target ?? "for this machine"} failed`);
}

/** The JSON Schemas of the contract, as committed in schemas/. */
export async function schemaFiles(): Promise<Record<string, string>> {
  const { SCHEMAS, jsonSchema } = await import("../src/contract/schemas.ts");
  return Object.fromEntries(
    Object.keys(SCHEMAS).map((name) => [
      `${name}.schema.json`,
      `${JSON.stringify(jsonSchema(name as keyof typeof SCHEMAS), null, 2)}\n`,
    ]),
  );
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args[0] === "--schemas") {
    ensureDir(join(ROOT, "schemas"));
    for (const [file, text] of Object.entries(await schemaFiles())) writeFileSync(join(ROOT, "schemas", file), text);
    console.log("built schemas/");
  } else {
    if (await buildAssets()) console.log("built src/report/assets.gen.ts");
    if (args[0] === "--compile") compile(args.length > 1 ? args.slice(1) : [...TARGETS]);
    else if (args[0] !== "--assets") await buildNode();
  }
}
